"""Sound: background music + sound effects + voice, mixed in numpy.

Everything is generated by code (no downloads, no licences to worry about).
Want real music instead? Drop royalty-free .wav/.mp3 files into assets/music/
(e.g. YouTube Audio Library tracks) and one is picked at random each day.
"""
import random
import subprocess

import numpy as np
import soundfile as sf

from .common import ROOT, db_to_gain, log

SR = 48000


# ---------------- small DSP helpers ----------------
def _env(n, attack=0.005, release=0.2):
    t = np.arange(n) / SR
    a = np.clip(t / max(attack, 1e-4), 0, 1)
    r = np.exp(-t / max(release, 1e-4))
    return a * r


def _lowpass(x, cutoff):
    alpha = np.exp(-2 * np.pi * cutoff / SR)
    y = np.empty_like(x)
    acc = 0.0
    for i in range(len(x)):  # fine for short sounds
        acc = (1 - alpha) * x[i] + alpha * acc
        y[i] = acc
    return y


def _lp_fast(x, cutoff):
    """Cheap lowpass for long signals via FFT."""
    X = np.fft.rfft(x)
    f = np.fft.rfftfreq(len(x), 1 / SR)
    X *= 1 / np.sqrt(1 + (f / cutoff) ** 4)
    return np.fft.irfft(X, n=len(x))


def _bandsweep_noise(n, f0, f1, q=3.0, rng=None):
    rng = rng or np.random.default_rng(1)
    noise = rng.standard_normal(n)
    out = np.zeros(n)
    block = 1024
    for s in range(0, n, block):
        frac = s / max(n - 1, 1)
        fc = f0 * (f1 / f0) ** frac
        seg = noise[s:s + block]
        X = np.fft.rfft(seg, n=block)
        f = np.fft.rfftfreq(block, 1 / SR)
        X *= np.exp(-((np.log2(np.maximum(f, 1) / fc)) ** 2) * q)
        out[s:s + block] = np.fft.irfft(X, n=block)[: len(seg)]
    return out / (np.max(np.abs(out)) + 1e-9)


# ---------------- sound effects ----------------
def sfx_whoosh():
    n = int(0.45 * SR)
    x = _bandsweep_noise(n, 300, 4000)
    t = np.linspace(0, 1, n)
    return x * np.sin(np.pi * t) ** 2 * 0.9


def sfx_hit():
    n = int(0.6 * SR)
    t = np.arange(n) / SR
    freq = 90 * np.exp(-t * 6) + 45
    body = np.sin(2 * np.pi * np.cumsum(freq) / SR) * _env(n, 0.002, 0.25)
    crack = np.random.default_rng(2).standard_normal(n) * _env(n, 0.001, 0.03) * 0.5
    return np.tanh((body + crack) * 2.2) * 0.9


def sfx_pop():
    n = int(0.09 * SR)
    t = np.arange(n) / SR
    freq = 1100 * np.exp(-t * 35) + 300
    return np.sin(2 * np.pi * np.cumsum(freq) / SR) * _env(n, 0.001, 0.025)


def sfx_boing():
    n = int(0.55 * SR)
    t = np.arange(n) / SR
    freq = 180 + 140 * np.exp(-t * 4) * np.sin(2 * np.pi * 14 * t) + 120 * (1 - t / t[-1])
    return np.sin(2 * np.pi * np.cumsum(freq) / SR) * _env(n, 0.003, 0.3) * 0.8


def sfx_riser():
    n = int(1.0 * SR)
    t = np.linspace(0, 1, n)
    tone = np.sin(2 * np.pi * np.cumsum(200 + 900 * t ** 2) / SR)
    noise = _bandsweep_noise(n, 500, 6000, rng=np.random.default_rng(3))
    return (tone * 0.4 + noise * 0.5) * t ** 2


def sfx_tick():
    n = int(0.04 * SR)
    t = np.arange(n) / SR
    return np.sin(2 * np.pi * 2500 * t) * _env(n, 0.0005, 0.006)


SFX = {"whoosh": sfx_whoosh, "hit": sfx_hit, "pop": sfx_pop, "boing": sfx_boing,
       "riser": sfx_riser, "tick": sfx_tick}


# ---------------- music ----------------
def _note(midi):
    return 440.0 * 2 ** ((midi - 69) / 12)


def generated_music(seconds, seed):
    """A quiet, curious, slightly mysterious loop. Different every day."""
    rng = random.Random(seed)
    bpm = rng.choice([92, 96, 100, 104])
    root = rng.choice([45, 47, 48, 50, 52])  # A2..E3
    prog = rng.choice([[0, 8, 3, 10], [0, 5, 8, 7], [0, 3, 8, 10], [0, 10, 8, 7]])
    beat = 60 / bpm
    bar = beat * 4
    n = int(seconds * SR)
    out = np.zeros(n)
    t_all = np.arange(n) / SR

    # pad chords (filtered saw-ish via few harmonics)
    pad = np.zeros(n)
    for bi in range(int(seconds / bar) + 1):
        s, e = int(bi * bar * SR), min(n, int((bi + 1) * bar * SR))
        if s >= n:
            break
        chord_root = root + 12 + prog[bi % 4]
        tt = t_all[s:e] - bi * bar
        seg = np.zeros(e - s)
        for iv in (0, 3, 7):  # minor triad
            f = _note(chord_root + iv)
            for h, amp in ((1, 1.0), (2, 0.35), (3, 0.15)):
                seg += amp * np.sin(2 * np.pi * f * h * tt + h)
        fade = np.minimum(1, np.minimum(tt / 0.25, (bar - tt) / 0.25))
        pad[s:e] += seg * fade
    pad = _lp_fast(pad, 1400) * 0.06

    # plucky bass on beats 1 and 3, pulse on off-beats
    bass = np.zeros(n)
    hats = np.zeros(n)
    hrng = np.random.default_rng(seed)
    for k in range(int(seconds / beat) + 1):
        s = int(k * beat * SR)
        if s >= n:
            break
        bi = int(k // 4)
        if k % 2 == 0:
            ln = min(int(beat * 0.9 * SR), n - s)
            tt = np.arange(ln) / SR
            f = _note(root + prog[bi % 4])
            bass[s:s + ln] += np.tanh(2 * np.sin(2 * np.pi * f * tt)) * np.exp(-tt * 5) * 0.22
        hs = int((k + 0.5) * beat * SR)
        if hs < n:
            ln = min(int(0.05 * SR), n - hs)
            hats[hs:hs + ln] += hrng.standard_normal(ln) * np.exp(-np.arange(ln) / SR * 90) * 0.04
    kick = np.zeros(n)
    for k in range(0, int(seconds / beat) + 1, 2):
        s = int(k * beat * SR)
        if s >= n:
            break
        ln = min(int(0.3 * SR), n - s)
        tt = np.arange(ln) / SR
        kick[s:s + ln] += np.sin(2 * np.pi * np.cumsum(55 + 90 * np.exp(-tt * 30)) / SR) * np.exp(-tt * 9) * 0.35
    hats = hats - _lp_fast(hats, 5000)
    out = pad + bass + kick + hats
    fade_in = np.clip(t_all / 1.0, 0, 1)
    fade_out = np.clip((seconds - t_all) / 1.5, 0, 1)
    out *= fade_in * fade_out
    return out / (np.max(np.abs(out)) + 1e-9)


def load_music(seconds, seed):
    files = sorted([p for p in (ROOT / "assets/music").glob("*") if p.suffix.lower() in (".wav", ".mp3", ".ogg", ".m4a")])
    if not files:
        return generated_music(seconds, seed)
    f = random.Random(seed).choice(files)
    log(f"Music: {f.name}")
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(f), "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"],
                         capture_output=True, check=True).stdout
    x = np.frombuffer(raw, dtype=np.float32).astype(np.float64)
    if len(x) == 0:
        return generated_music(seconds, seed)
    reps = int(np.ceil(seconds * SR / len(x)))
    x = np.tile(x, reps)[: int(seconds * SR)]
    t = np.arange(len(x)) / SR
    x *= np.clip((seconds - t) / 1.5, 0, 1)
    return x / (np.max(np.abs(x)) + 1e-9)


# ---------------- mix ----------------
def sfx_cues(cfg, script, timeline, caption_times):
    """Every sound effect as (name, seconds, relative gain). Shared by the ffmpeg mix and Remotion."""
    cues = []
    for i, (sc, line) in enumerate(zip(script["scenes"], timeline)):
        if i > 0:  # swish on every cut, louder on whip/zoom transitions
            loud = 0.75 if sc.get("transition") in ("whip", "zoom") else 0.3
            cues.append(("whoosh", line["start"] - 0.22, loud))
        kind = sc.get("sfx", "none")
        if kind != "none" and kind in SFX:
            at = line["start"]
            emph = sc.get("emphasis", "").lower()
            for w in line["words"]:
                if emph and emph in w["word"].lower():
                    at = w["start"]
                    break
            if kind == "riser":
                at -= 0.9
            cues.append((kind, at, 1.0))
    if cfg["audio"].get("caption_pops"):
        cues += [("pop", ct, 0.18) for ct in caption_times]
    return [(n, max(0.0, at), g) for n, at, g in cues]


def mix(cfg, script, timeline, caption_times, voice_path, total, workdir, seed, with_sfx=True):
    a = cfg["audio"]
    voice, vsr = sf.read(voice_path, dtype="float64")
    if voice.ndim > 1:
        voice = voice.mean(axis=1)
    # resample voice 24k -> 48k (linear is fine for speech at 2x)
    idx = np.arange(int(len(voice) * SR / vsr)) * vsr / SR
    voice = np.interp(idx, np.arange(len(voice)), voice)
    n = int(total * SR)
    v = np.zeros(n)
    v[: min(n, len(voice))] = voice[:n]
    v = v / (np.max(np.abs(v)) + 1e-9) * 0.9

    # music with ducking under the voice
    music = load_music(total, seed)[:n]
    music = np.pad(music, (0, n - len(music)))
    hop = int(0.02 * SR)
    rms = np.sqrt(np.convolve(v ** 2, np.ones(hop) / hop, mode="same"))
    duck = 1 - 0.55 * np.clip(rms / 0.08, 0, 1)
    duck = _lp_fast(duck, 6)  # smooth
    music = music * db_to_gain(a["music_volume_db"]) * np.clip(duck, 0.3, 1)

    fx = np.zeros(n)
    gain = db_to_gain(a["sfx_volume_db"])

    def place(sound, at, g=1.0):
        s = int(max(0, at) * SR)
        if s >= n:
            return
        e = min(n, s + len(sound))
        fx[s:e] += sound[: e - s] * g

    if with_sfx:
        cache = {k: f() for k, f in SFX.items()}
        for name, at, g in sfx_cues(cfg, script, timeline, caption_times):
            place(cache[name], at, gain * g)

    out = v + music + fx
    peak = np.max(np.abs(out)) + 1e-9
    if peak > 0.98:
        out = out / peak * 0.98
    path = workdir / "mix.wav"
    sf.write(path, out.astype(np.float32), SR)
    return path
